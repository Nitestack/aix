#!/usr/bin/env bash
# render.sh — generate package-manager manifests for a published release.
#
# Usage: scripts/packaging/render.sh <version> <SHA256SUMS> <outdir>
#
# Writes:
#   <outdir>/homebrew/Formula/aix.rb   → get-aix/homebrew-tap
#   <outdir>/scoop/bucket/aix.json     → get-aix/scoop-bucket
#   <outdir>/aur/PKGBUILD              → AUR package aix-rs-bin
set -euo pipefail

if [ "$#" -ne 3 ]; then
    echo "usage: $0 <version> <SHA256SUMS> <outdir>" >&2
    exit 2
fi

version="${1#v}"
sums="$2"
out="$3"

repo_url="https://github.com/get-aix/aix"
dl="${repo_url}/releases/download/v${version}"
desc="Launch AI coding tools with the right AI gateway profile and credentials"

sha() {
    local value
    value="$(awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }' "$sums")"
    if [ -z "$value" ]; then
        echo "error: no checksum for $1 in $sums" >&2
        exit 1
    fi
    printf '%s' "$value"
}

mac_arm="$(sha aix-aarch64-apple-darwin)"
mac_x64="$(sha aix-x86_64-apple-darwin)"
linux_arm="$(sha aix-aarch64-unknown-linux-musl)"
linux_x64="$(sha aix-x86_64-unknown-linux-musl)"
win_x64="$(sha aix-x86_64-pc-windows-msvc.exe)"

mkdir -p "$out/homebrew/Formula" "$out/scoop/bucket" "$out/aur"

cat > "$out/homebrew/Formula/aix.rb" <<EOF
# Generated by get-aix/aix scripts/packaging/render.sh — do not edit by hand.
class Aix < Formula
  desc "${desc}"
  homepage "${repo_url}"
  version "${version}"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
      url "${dl}/aix-aarch64-apple-darwin"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "${dl}/aix-x86_64-apple-darwin"
      sha256 "${mac_x64}"
    end
  end

  on_linux do
    on_arm do
      url "${dl}/aix-aarch64-unknown-linux-musl"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${dl}/aix-x86_64-unknown-linux-musl"
      sha256 "${linux_x64}"
    end
  end

  def install
    bin.install Dir["aix-*"].first => "aix"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/aix --version")
  end
end
EOF

cat > "$out/scoop/bucket/aix.json" <<EOF
{
    "version": "${version}",
    "description": "${desc}",
    "homepage": "${repo_url}",
    "license": "AGPL-3.0-only",
    "architecture": {
        "64bit": {
            "url": "${dl}/aix-x86_64-pc-windows-msvc.exe#/aix.exe",
            "hash": "${win_x64}"
        }
    },
    "bin": "aix.exe",
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "${repo_url}/releases/download/v\$version/aix-x86_64-pc-windows-msvc.exe#/aix.exe"
            }
        }
    }
}
EOF

cat > "$out/aur/PKGBUILD" <<EOF
# Generated by get-aix/aix scripts/packaging/render.sh — do not edit by hand.
pkgname=aix-rs-bin
pkgver=${version}
pkgrel=1
pkgdesc="${desc}"
arch=('x86_64' 'aarch64')
url="${repo_url}"
license=('AGPL-3.0-only')
provides=('aix')
conflicts=('aix' 'aix-bin')
options=('!strip' '!debug')
source_x86_64=("aix-\${pkgver}-x86_64::${repo_url}/releases/download/v\${pkgver}/aix-x86_64-unknown-linux-musl")
source_aarch64=("aix-\${pkgver}-aarch64::${repo_url}/releases/download/v\${pkgver}/aix-aarch64-unknown-linux-musl")
sha256sums_x86_64=('${linux_x64}')
sha256sums_aarch64=('${linux_arm}')

package() {
    install -Dm755 "aix-\${pkgver}-\${CARCH}" "\${pkgdir}/usr/bin/aix"
}
EOF

echo "Rendered manifests for v${version} into ${out}"
